vector<double> read_eri(fs::path p) {
  ifstream file(p);
  int i,j,k,l;
  double val;
  vector<double> v;
  while (file>>i>>j>>k>>l>>val) {
    i--,j--,k--,l--;
    v[(pair_index(i,j),pair_index(k,l))] = val;
  }
  return v;
}


